#!/usr/bin/env python3
"""Run the selected complete k=11 computational route, including k<=10.

Read verification-eleven.md for the mathematical premises and trusted code.
A fresh output directory is required for independent reproduction. --resume
uses only the local checkpoints made there; receipts are not certificates.
"""
import argparse
import fcntl
import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys
import time

from replay_cache import atomic_json, digest

ROOT = Path(__file__).resolve().parents[1]
GENREG_FILES = ('gendef.h', 'genreg.c', 'main.c', 'optmid.c')


def stages(source, output, workers, resume):
    def script(name, *args):
        return [sys.executable, '-u', str(ROOT / name), *map(str, args)]
    s = 'scripts/'
    archive = 'research/eleven/scripts/'
    return [
        ('earlier-classifications', script(s+'reproduce_ten.py', '--full',
            '--genreg-source', source, '--workers', workers, '--output', output/'earlier')),
        ('witness', script(s+'verify_witness53.py')),
        ('order23', script(s+'verify_order23_anchor_finish.py',
            ROOT/'sources/eleven-order23-refutations.bin.xz', '--workers', workers)),
        ('order24', script(s+'verify_order24_compact.py', '--check-premises', '--native')),
        ('order25', script(s+'verify_order25_complete.py', '--check-new-premises', '--native',
            '--workers', workers, '--output', output/'order25.json')),
        ('triangles', script(s+'verify_triangle_refutation.py',
            ROOT/'sources/eleven-quartic-triangle-coverage.json.xz',
            ROOT/'sources/eleven-quartic-triangle-refutations.json.xz')),
        # The marked-H22 theorem is regenerated by order24 --check-premises.
        ('quartic-exception', script(s+'verify_exceptional_quartic_square.py', '--native')),
        ('four-squares', script(s+'verify_quartic_four_square.py')),
        ('square-path', script(s+'verify_quartic_path_refutation.py', '--workers', workers)),
        ('square-roots', script(s+'verify_eleven_square_roots.py')),
        ('girth-five', script(archive+'run_treewidth_eleven_girth.py', '--genreg-source', source,
            '--workers', workers, '--output', output/'girth-five')),
        ('girth-five-audit', script(archive+'audit_treewidth_eleven_girth.py', output/'girth-five')),
        ('square-searches', script(s+'replay_eleven.py', '--scope', 'quartic', '--replay-terminals',
            '--workers', workers, '--output', output/'squares',
            *(['--resume'] if resume and (output/'squares/restore.json').exists() else []))),
    ]


def inventory():
    return {str(p.relative_to(ROOT)): digest(p)
            for directory in ('scripts', 'sources', 'research/eleven')
            for p in sorted((ROOT/directory).rglob('*'))
            if p.is_file() and '__pycache__' not in p.parts}


def validate_summary(path, **expected):
    report = json.loads(path.read_text())
    if any(report.get(k) != v for k, v in expected.items()):
        raise RuntimeError(f'Incomplete or unexpected report: {path}')


def main():
    if not __debug__ or os.environ.get('PYTHONOPTIMIZE'):
        raise RuntimeError('Run without Python optimization: assertions verify certificates.')
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--genreg-source', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--workers', type=int, default=min(8, os.cpu_count() or 1))
    parser.add_argument('--resume', action='store_true')
    parser.add_argument('--plan', action='store_true', help='Print every command without running or writing anything.')
    args = parser.parse_args()
    if args.workers < 1 or sys.version_info < (3, 11):
        parser.error('Positive worker count and Python 3.11 or later required.')
    output, source = args.output.resolve(), args.genreg_source.resolve()
    if output == ROOT or ROOT in output.parents:
        parser.error('Choose an output directory outside the checkout.')
    selected = stages(source, output, args.workers, args.resume)
    if args.plan:
        for name, command in selected:
            print(name + ': ' + shlex.join(command))
        return
    for name in GENREG_FILES:
        if not (source/name).is_file():
            parser.error(f'Missing GENREG r5 source: {source/name}')
    bubblewrap = shutil.which('bwrap')
    if not bubblewrap:
        parser.error('Install bubblewrap; see verification-eleven.md for prerequisites.')
    subprocess.run([bubblewrap, '--ro-bind', '/', '/', '/bin/true'], check=True)
    for command in (['pkg-config', '--exists', 'nauty'],
                    [*shlex.split(os.environ.get('CC', 'cc')), '--version']):
        subprocess.run(command, check=True, stdout=subprocess.DEVNULL)
    output.mkdir(parents=True, exist_ok=args.resume)
    with (output/'.verification.lock').open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        inputs = {'format': 1, 'files': inventory(), 'python': sys.version,
                  'python_executable': digest(sys.executable), 'workers': args.workers,
                  'genreg': {name: digest(source/name) for name in GENREG_FILES},
                  'genreg_directory': str(source),
                  'environment': {k: os.environ.get(k) for k in ('CC', 'GENG_SOURCE', 'CFLAGS')}}
        manifest = output/'inputs.json'
        if args.resume:
            if not manifest.exists() or json.loads(manifest.read_text()) != inputs:
                raise RuntimeError('Inputs changed or manifest missing; use a fresh output directory.')
        else:
            atomic_json(manifest, inputs)
        (output/'logs').mkdir(exist_ok=True)
        completed = {}
        report_path = output/'summary.json'
        if args.resume and report_path.exists():
            completed = json.loads(report_path.read_text())['stages']
        def save(status):
            atomic_json(report_path, {'status': status, 'stages': completed,
                        'inputs_sha256': digest(manifest),
                        'scope': 'Selected computational checks, including earlier classifications. '
                                 'Written reductions and enumeration correctness remain premises.'})
        save('running')
        for name, command in selected:
            log = output/'logs'/f'{name}.log'
            prior = completed.get(name)
            if prior and prior['status'] == 'passed' and log.exists() and digest(log) == prior['log_sha256']:
                print(f'{name}: using successful local check', flush=True)
                continue
            print(f'{name}: running; log {log}', flush=True)
            started = time.monotonic()
            with log.open('w') as stream:
                result = subprocess.run(command, cwd=ROOT, stdout=stream, stderr=subprocess.STDOUT,
                                        env={**os.environ, 'PYTHONDONTWRITEBYTECODE': '1'})
            completed[name] = {'status': 'passed' if result.returncode == 0 else 'failed',
                               'returncode': result.returncode, 'command': command,
                               'seconds': time.monotonic()-started, 'log_sha256': digest(log)}
            save('running' if result.returncode == 0 else 'incomplete')
            if result.returncode:
                raise RuntimeError(f'{name} failed (exit {result.returncode}); see {log}')
            print(f'{name}: passed in {completed[name]["seconds"]:.1f}s', flush=True)
        validate_summary(output/'earlier/summary.json', status='complete', mode='full', minimum_edges=47)
        validate_summary(output/'girth-five/summary.json', status='complete', completed_parts=256)
        validate_summary(output/'squares/treewidth11/resumable-quartic/summary.json',
                         status='required_replays_verified', terminal_replays=True, covered_roots=5)
        if inventory() != inputs['files']:
            raise RuntimeError('Repository inputs changed during verification.')
        save('complete')
        print('PASS: all selected computational checks completed. See verification-eleven.md for written premises.')


if __name__ == '__main__':
    main()
